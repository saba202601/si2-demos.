"""Install SI² Financial Reporting on SQL Server (schema fin in SI2Canonical) or SQLite.

    set SI2_SQL_SERVER=SABAHOME\\SQLEXPRESS02
    set SI2_SQL_DATABASE=SI2Canonical
    python -m finance.install              # create tables, load the Yellow Book, the ontology and the synthetic source
    python -m finance.install --no-source  # tables, Yellow Book and ontology only (connect your own feeds later)
    python -m finance.install --scripts    # (re)write finance/sql/01_create_fin.sql and 02_seed_yellowbook.sql

Then open SI² Studio > Financial Reporting: step 3 can connect to the fin.Src* tables (or your own views).
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

import pandas as pd

from . import blank, db, ontology, source

SQL_DIR = Path(__file__).resolve().parent / "sql"


def _sql_lit(v) -> str:
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "NULL"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return repr(v)
    return "N'" + str(v).replace("'", "''") + "'"


def write_scripts() -> list[Path]:
    SQL_DIR.mkdir(exist_ok=True)
    p1 = SQL_DIR / "01_create_fin.sql"
    p1.write_text(db.ddl("mssql"), encoding="utf-8")
    fc = ontology.field_concepts()
    frames = {"YbPage": blank.pages(), "YbLine": blank.lines(), "YbColumn": blank.columns(),
              "YbField": blank.fields().merge(fc, on="field_id", how="left"), "YbAslLine": blank.asl(),
              "OntConcept": ontology.concepts(), "OntRelation": ontology.relations().drop_duplicates(["subject_id", "predicate", "object_id"])}
    out = ["-- SI² Financial Reporting: the NAIC P&C Annual Statement (Yellow Book) fields and the financial reporting ontology.",
           "-- Generated by finance/install.py --scripts. Run 01_create_fin.sql first. Reloads these tables completely.",
           "SET NOCOUNT ON;", "GO"]
    for name, df in frames.items():
        cols = [c for c, _t, _n in db.TABLES[name][0]]
        df = df.reindex(columns=cols)
        out.append(f"DELETE FROM fin.{name};")
        rows = [", ".join(_sql_lit(db._py(v)) for v in r) for r in df.itertuples(index=False)]
        for i in range(0, len(rows), 900):
            out.append(f"INSERT INTO fin.{name} ({', '.join(cols)}) VALUES\n(" + "),\n(".join(rows[i:i + 900]) + ");")
        out.append("GO")
    p2 = SQL_DIR / "02_seed_yellowbook.sql"
    p2.write_text("\n".join(out) + "\n", encoding="utf-8")
    return [p1, p2]


def install(with_source: bool = True, dialect: str | None = None) -> dict:
    t0 = time.time()
    d = db.Db(dialect)
    print("Financial Reporting install on", d.describe())
    d.create()
    n = db.load_catalog(d, ontology.concepts(), ontology.relations(), ontology.field_concepts())
    if with_source:
        n.update(db.load_source(d, source.build()))
    for k, v in n.items():
        print(f"  {d.t(k):28s} {v:>9,} rows")
    print(f"  done in {time.time() - t0:.0f} s")
    return n


if __name__ == "__main__":
    if "--scripts" in sys.argv:
        for p in write_scripts():
            print("wrote", p)
    else:
        install(with_source="--no-source" not in sys.argv)
