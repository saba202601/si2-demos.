CREATE TABLE AGENT (
  AGENT_NO      VARCHAR2(10)  NOT NULL,
  AGENT_NM      VARCHAR2(60)  NOT NULL,
  AGENCY_STATE  CHAR(2),
  APPOINTED_DT  DATE,
  CONSTRAINT PK_AGENT PRIMARY KEY (AGENT_NO)
);

CREATE TABLE POLICY (
  POL_NO        VARCHAR2(12)  NOT NULL,
  EFF_DT        DATE          NOT NULL,
  EXP_DT        DATE          NOT NULL,
  INSURED_NM    VARCHAR2(80),
  STATE_CD      CHAR(2),
  ZIP_CD        VARCHAR2(10),
  LOB_CD        VARCHAR2(5),
  WRITTEN_PREM  NUMBER(12,2),
  AGENT_NO      VARCHAR2(10),
  POL_STATUS    CHAR(1),
  CONSTRAINT PK_POLICY PRIMARY KEY (POL_NO, EFF_DT),
  CONSTRAINT FK_POLICY_AGENT FOREIGN KEY (AGENT_NO) REFERENCES AGENT (AGENT_NO)
);

